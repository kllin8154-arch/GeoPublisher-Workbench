"""Opt-in business catalog registration against an explicitly authorized PostgreSQL.

The reviewed profile, recent read-only evidence, live preflight and typed
authorization must all agree. SQL is generated by business_tree, never loaded
from an arbitrary file. Unknown commit outcomes are never automatically retried.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import psycopg
from psycopg import sql

from .business_tree import _node_values, _service_values, build_business_tree_sql
from .catalog import _identifier
from .catalog_live import (
    DatabaseReviewError,
    _read_snapshot,
    assess_catalog_snapshot,
    review_mapping,
)
from .server_forward import open_service


def _reject(message: str, code: str = "CATALOG_REGISTRATION_BLOCKED") -> None:
    raise DatabaseReviewError(code, message)


def registration_phrase(database: str, profile_digest: str) -> str:
    """Human acknowledgement is tied to a database and exact reviewed JSON."""
    _identifier(database)
    if len(profile_digest) != 64 or any(c not in "0123456789abcdef" for c in profile_digest):
        _reject("业务目录文件摘要格式无效。")
    return f"REGISTER {database} {profile_digest[:12]}"


def _review_evidence(path: Path | str, *, source: Path, digest: str,
                     target: dict, database: str, schema: str) -> dict:
    if str(path).startswith(("\\", "//")):
        _reject("只读核验报告必须位于本机磁盘。")
    file = Path(path).expanduser().absolute()
    if (file.name != "business_db_readonly_review.json" or not file.is_file()
            or file.is_symlink() or any(p.is_symlink() for p in file.parents)
            or file.stat().st_size > 2 * 1024 * 1024):
        _reject("只读核验报告不存在或不符合本机文件限制。")
    try:
        evidence = json.loads(file.read_text(encoding="utf-8-sig"))
        identity = evidence["database_identity"]
        if (evidence["status"] != "READ_ONLY_EVIDENCE_READY_NOT_APPROVED"
                or evidence["blocking_reasons"] or evidence["sql_executed"] is not False
                or evidence["database_modified"] is not False
                or evidence["review_required"] is not True
                or evidence["review_file_sha256"] != digest
                or Path(evidence["source_review_file"]).absolute() != source
                or evidence["target"] != target
                or identity["database"] != database or identity["schema"] != schema
                or identity["read_only"] != "on"):
            raise ValueError()
    except (ValueError, TypeError, KeyError, OSError) as exc:
        raise DatabaseReviewError(
            "CATALOG_EVIDENCE_MISMATCH",
            "只读核验报告与本次目录/数据库/服务器不一致；请重新运行只读核验。",
        ) from exc
    return evidence


def _audit(destination: Path, **values) -> None:
    """Write a durable local intent before the database can be touched."""
    path = destination / "catalog_registration_audit.json"
    temp = destination / "catalog_registration_audit.json.pending"
    with temp.open("w", encoding="utf-8") as output:
        json.dump(values, output, ensure_ascii=False, indent=2, sort_keys=True)
        output.write("\n")
        output.flush()
        os.fsync(output.fileno())
    os.replace(temp, path)


def _post_verify(conn, profile: dict) -> list[str]:
    """Read all registered mapped columns, not merely the number of new rows."""
    schema = profile["target_schema"]
    tables, columns, defaults = profile["tables"], profile["columns"], profile["defaults"]
    failures: list[str] = []
    conn.execute("BEGIN READ ONLY")
    try:
        conn.execute(sql.SQL("SET LOCAL search_path TO {}, pg_catalog, pg_temp").format(
            sql.Identifier(schema)
        ))
        identity = conn.execute(
            "SELECT current_database(), current_schema(), current_setting('transaction_read_only')"
        ).fetchone()
        if identity[1:] != (schema, "on"):
            _reject("数据库回查时目标 schema 或只读状态已改变。")
        nodes = [
            (node, _node_values(node, defaults, group=True))
            for node in profile["groups"]
        ] + [
            (node, _node_values(node, defaults, group=False))
            for node in profile["layers"]
        ]
        for item, values in nodes:
            if _row_matches(conn, tables["node"], columns["node"], values) != 1:
                failures.append("node:" + item["code"])
        services = {_service_values(layer, defaults)["key"]: _service_values(layer, defaults)
                    for layer in profile["layers"]}
        for key, values in services.items():
            if _row_matches(conn, tables["service"], columns["service"], values) != 1:
                failures.append("service:" + key)
    finally:
        conn.execute("ROLLBACK")
    return failures


def _row_matches(conn, table: str, mapping: dict, values: dict) -> int:
    fields = [(actual, values[logical]) for logical, actual in mapping.items() if logical in values]
    where = sql.SQL(" AND ").join(
        sql.SQL("{} IS NOT DISTINCT FROM %s").format(sql.Identifier(column))
        for column, _ in fields
    )
    statement = sql.SQL("SELECT COUNT(*) FROM {} WHERE {}").format(
        sql.Identifier(table), where
    )
    return int(conn.execute(statement, [value for _, value in fields]).fetchone()[0])


def register_catalog(
    target, session, profile_file: Path | str, evidence_file: Path | str,
    *, database: str, username: str, password: str, output: Path | str,
    confirmation: str, connect=psycopg.connect,
) -> dict:
    """Register approved nodes with one explicit, non-retryable write attempt."""
    source, profile, digest = review_mapping(profile_file)
    _identifier(database)
    _identifier(username)
    if profile["target_schema"].casefold().startswith("pg_") or profile["target_schema"] == "information_schema":
        _reject("系统 schema 不能用于业务目录登记。")
    if profile["schema_verified"] is not True:
        _reject("业务表结构尚未由实施人员明确核实。")
    if not password:
        _reject("登记操作需要本次输入的 PostgreSQL 写权限账号密码。")
    _review_evidence(evidence_file, source=source, digest=digest,
                     target=target.safe_info(), database=database,
                     schema=profile["target_schema"])
    phrase = registration_phrase(database, digest)
    if confirmation != phrase:
        _reject("登记确认短语不匹配，未连接数据库。", "CATALOG_CONFIRMATION_REQUIRED")

    if str(output).startswith(("\\", "//")):
        _reject("审计目录必须在本机磁盘。")
    destination = Path(output).expanduser().absolute()
    if (destination.exists() or destination.is_symlink()
            or any(parent.is_symlink() for parent in destination.parents)
            or not destination.parent.is_dir()):
        _reject("本次登记必须使用一个已有本机父目录下的全新审计目录，不能覆盖旧任务。")
    destination.mkdir(parents=True, exist_ok=False)
    sql_package = build_business_tree_sql(profile, destination / "generated_sql")
    if sql_package["status"] != "SQL_GENERATED_NOT_EXECUTED":
        _audit(destination, status="BLOCKED_WITHOUT_WRITE",
               blocked=sql_package["blocked"], profile_sha256=digest, database=database)
        _reject("业务分类、来源转换、WMS 或 schema 未全部审核；拒绝执行 SQL。")
    generated = Path(sql_package["registration_sql"])
    sql_text = generated.read_text(encoding="utf-8")
    script_hash = hashlib.sha256(sql_text.encode("utf-8")).hexdigest()
    base_audit = {
        "database": database, "schema": profile["target_schema"],
        "target": target.safe_info(), "database_user": username,
        "profile_sha256": digest, "sql_sha256": script_hash,
        "group_count": len(profile["groups"]), "layer_count": len(profile["layers"]),
        "password_saved": False, "automatic_retry": False,
    }
    with open_service(session, service="postgres") as tunnel:
        try:
            with connect(
                host="127.0.0.1", port=tunnel.port, dbname=database,
                user=username, password=password, connect_timeout=10,
                autocommit=True, sslmode="disable",
                options="-c statement_timeout=60000 -c lock_timeout=5000 "
                        "-c idle_in_transaction_session_timeout=90000",
                application_name="geopublisher_catalog_authorized_registration",
            ) as conn:
                snapshot = _read_snapshot(conn, profile, database=database)
                check = assess_catalog_snapshot(profile, snapshot)
                if check["status"] != "READ_ONLY_EVIDENCE_READY_NOT_APPROVED":
                    _audit(destination, **base_audit, status="BLOCKED_WITHOUT_WRITE",
                           blocked=check["blocking_reasons"])
                    _reject("写入前重新核验发现业务表、父节点或服务冲突，已停止。")
                _audit(destination, **base_audit, status="WRITE_INTENT_DURABLE_NOT_YET_CONFIRMED")
                try:
                    # Includes BEGIN, reviewed tables LOCK, collision guards and COMMIT.
                    # No arbitrary SQL file from a caller is ever executed.
                    cursor = conn.execute(sql_text)
                    # psycopg returns a cursor at the first result set. Drain
                    # all statements so a later INSERT/COMMIT failure is not
                    # mistaken for a successful first BEGIN/LOCK response.
                    while cursor.nextset():
                        pass
                except Exception as exc:
                    try:
                        conn.execute("ROLLBACK")
                    except Exception:
                        pass
                    _audit(destination, **base_audit, status="MANUAL_RECONCILIATION_REQUIRED",
                           note="数据库提交状态不能可靠证明；必须只读核对后人工处理。")
                    raise DatabaseReviewError(
                        "CATALOG_OUTCOME_UNKNOWN",
                        "数据库执行中断或出错，提交结果需要人工核对；禁止直接重试。",
                    ) from exc
                _audit(destination, **base_audit, status="COMMITTED_PENDING_READONLY_VERIFICATION")
                try:
                    missing = _post_verify(conn, profile)
                    if missing:
                        raise ValueError("Post-registration row verification incomplete")
                except Exception as exc:
                    _audit(destination, **base_audit, status="MANUAL_RECONCILIATION_REQUIRED",
                           note="SQL 提交后未能完整只读回查所有节点/服务。")
                    raise DatabaseReviewError(
                        "CATALOG_VERIFY_UNKNOWN",
                        "数据库可能已写入，但只读回查不完整；禁止直接重试。",
                    ) from exc
        except psycopg.Error as exc:
            # Failure even before WRITE_INTENT: do not invent a success result.
            raise DatabaseReviewError(
                "CATALOG_CONNECTION_FAILED",
                "目标数据库连接或查询失败，请核对授权的 206 内网环境与权限。",
            ) from exc
    _audit(destination, **base_audit, status="VERIFIED_REGISTERED",
           verified_group_count=len(profile["groups"]),
           verified_layer_count=len(profile["layers"]))
    return {
        "status": "VERIFIED_REGISTERED", "registered": True, "database_modified": True,
        "target": target.safe_info(),
        "audit_directory": str(destination), "database": database,
        "groups": len(profile["groups"]), "layers": len(profile["layers"]),
        "services_verified": len({layer["service_key"] for layer in profile["layers"]}),
    }
