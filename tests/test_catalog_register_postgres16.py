"""Dedicated disposable PostgreSQL 16 integration for authorized catalog registration.

Guarded by GEOPUB_SYNTHETIC_PG16_TEST=1 and fixed demo database credentials.
Never connect to a real GIS or production database.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from types import SimpleNamespace

import psycopg
import pytest
from test_catalog_live_postgres16 import SYNTHETIC_ADMIN_SECRET

from geopublisher.catalog_live import probe_catalog
from geopublisher.catalog_register import register_catalog, registration_phrase
from geopublisher.server_deploy import LinuxTarget

pytestmark = pytest.mark.integration


@pytest.fixture
def isolated_registry():
    if os.environ.get("GEOPUB_SYNTHETIC_PG16_TEST") != "1":
        pytest.skip("Only run against an explicitly selected disposable PG16 service")
    port = int(os.environ.get("GEOPUB_SYNTHETIC_PG16_PORT", "5432"))
    with psycopg.connect(
        host="127.0.0.1", port=port, dbname="demo_db", user="admin",
        password=SYNTHETIC_ADMIN_SECRET, connect_timeout=5, autocommit=True,
    ) as db:
        version = int(db.execute("SHOW server_version_num").fetchone()[0])
        assert 160000 <= version < 170000
        exists = db.execute(
            "SELECT COUNT(*) FROM pg_namespace WHERE nspname='demo_catalog_registration'"
        ).fetchone()[0]
        assert exists == 0, "Refuse preexisting schema, even in test database"
        db.execute("CREATE SCHEMA demo_catalog_registration")
        try:
            db.execute(
                "CREATE TABLE demo_catalog_registration.demo_nodes("
                "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                "sys varchar(8) NOT NULL,code varchar(128) NOT NULL,namec varchar(160) NOT NULL,"
                "glcode varchar(128),type varchar(30),disporder int,visible int,"
                "zooms int,zoome int,svr_name varchar(128),lay_idx int,"
                "UNIQUE(sys,code))"
            )
            db.execute(
                "CREATE TABLE demo_catalog_registration.demo_services("
                "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                "code varchar(128) NOT NULL UNIQUE,namec varchar(160),type varchar(30),"
                "platform varchar(64),url varchar(160),layer varchar(160),crs varchar(40),"
                "format varchar(64))"
            )
            db.execute(
                "INSERT INTO demo_catalog_registration.demo_nodes(sys,code,namec) "
                "VALUES('0','basemap','Basemap')"
            )
            yield port
        finally:
            # Only destroy the synthetic schema created above, never site schemas.
            db.execute("DROP SCHEMA demo_catalog_registration CASCADE")


def test_pg16_registration_commit_exact_children_recheck_and_repeat_block(
    isolated_registry, tmp_path: Path,
):
    from test_catalog_register import approved_review

    target, source, _evidence, digest, profile = approved_review(tmp_path)
    profile["target_schema"] = "demo_catalog_registration"
    source.write_text(json.dumps(profile, ensure_ascii=False), encoding="utf-8")
    target = LinuxTarget(mode="local", root="/srv/geopublisher/synthetic",
                         postgres_port=isolated_registry)
    session = SimpleNamespace(target=target)
    probe = probe_catalog(
        target, session, source, database="demo_db", username="admin",
        password=SYNTHETIC_ADMIN_SECRET, output=tmp_path / "evidence",
    )
    assert probe["status"] == "READ_ONLY_EVIDENCE_READY_NOT_APPROVED"
    report = json.loads(Path(probe["review"]).read_text("utf-8"))
    assert report["database_identity"]["read_only"] == "on"
    digest = report["review_file_sha256"]
    result = register_catalog(
        target, session, source, probe["review"],
        database="demo_db", username="admin", password=SYNTHETIC_ADMIN_SECRET,
        output=tmp_path / "registration",
        confirmation=registration_phrase("demo_db", digest),
    )
    assert result["status"] == "VERIFIED_REGISTERED"
    assert result["groups"] == result["layers"] == result["services_verified"] == 1

    with psycopg.connect(
        host="127.0.0.1", port=isolated_registry, dbname="demo_db",
        user="admin", password=SYNTHETIC_ADMIN_SECRET,
    ) as db:
        nodes = db.execute(
            "SELECT code,glcode,sys,lay_idx FROM demo_catalog_registration.demo_nodes "
            "ORDER BY id"
        ).fetchall()
        services = db.execute(
            "SELECT code,layer,crs FROM demo_catalog_registration.demo_services"
        ).fetchall()
        assert nodes == [
            ("basemap", None, "0", None),
            ("geo_50k", "basemap", "0", 2),
            ("sheet_n1", "geo_50k", "0", 3),
        ]
        assert services == [("sample_service", "demo:sample_sheet", "EPSG:4490")]

    # Run again using the old read-only evidence: fresh live recheck blocks the
    # collision before executing SQL, not a duplicate INSERT.
    with pytest.raises(Exception):
        register_catalog(
            target, session, source, probe["review"],
            database="demo_db", username="admin", password=SYNTHETIC_ADMIN_SECRET,
            output=tmp_path / "repeated_registration",
            confirmation=registration_phrase("demo_db", digest),
        )
    with psycopg.connect(
        host="127.0.0.1", port=isolated_registry, dbname="demo_db",
        user="admin", password=SYNTHETIC_ADMIN_SECRET,
    ) as db:
        assert db.execute(
            "SELECT COUNT(*) FROM demo_catalog_registration.demo_nodes"
        ).fetchone()[0] == 3
