"""Real PostgreSQL 16 opt-in synthetic integration.

This test only runs when a dedicated CI service database is explicitly
selected via GEOPUB_SYNTHETIC_PG16_TEST=1. No user site database is accepted.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from types import SimpleNamespace

import psycopg
import pytest
from psycopg import sql
from test_catalog_live import sample_mapping

from geopublisher.catalog_live import probe_catalog
from geopublisher.server_deploy import LinuxTarget

pytestmark = pytest.mark.integration

SYNTHETIC_ADMIN_SECRET = "test-only-admin-pg16-2026"
SYNTHETIC_READONLY_SECRET = "test-only-readonly-pg16-2026"


@pytest.fixture
def isolated_postgres():
    if os.environ.get("GEOPUB_SYNTHETIC_PG16_TEST") != "1":
        pytest.skip("Only run against a dedicated, disposable PostgreSQL 16 CI service")
    host = "127.0.0.1"
    port = int(os.environ.get("GEOPUB_SYNTHETIC_PG16_PORT", "5432"))
    if not 1 <= port <= 65535:
        pytest.fail("Invalid synthetic PostgreSQL test port")
    with psycopg.connect(
        host=host, port=port, dbname="demo_db", user="admin",
        password=SYNTHETIC_ADMIN_SECRET, connect_timeout=5,
        autocommit=True,
    ) as admin:
        server_version = int(admin.execute("SHOW server_version_num").fetchone()[0])
        assert 160000 <= server_version < 170000, "Test must use PostgreSQL 16"
        assert admin.execute(
            "SELECT COUNT(*) FROM pg_namespace WHERE nspname='demo_catalog'"
        ).fetchone()[0] == 0, "Refuse any non-empty or existing test environment"
        admin.execute("CREATE SCHEMA demo_catalog")
        admin.execute(
            "CREATE TABLE demo_catalog.demo_nodes("
            "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            "sys varchar(8) NOT NULL,"
            "code varchar(128) NOT NULL,"
            "namec varchar(160) NOT NULL,"
            "glcode varchar(128), type varchar(30), disporder integer,"
            "visible integer, zooms integer, zoome integer,"
            "svr_name varchar(128), lay_idx integer)"
        )
        admin.execute(
            "CREATE TABLE demo_catalog.demo_services("
            "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            "code varchar(128) NOT NULL, namec varchar(160),"
            "type varchar(30), platform varchar(64), url varchar(160),"
            "layer varchar(160), crs varchar(40), format varchar(64))"
        )
        admin.execute(
            "INSERT INTO demo_catalog.demo_nodes(sys,code,namec) "
            "VALUES ('0','basemap','Basemap')"
        )
        admin.execute(sql.SQL(
            "CREATE ROLE readonly LOGIN PASSWORD {} NOSUPERUSER NOCREATEDB NOCREATEROLE"
        ).format(sql.Literal(SYNTHETIC_READONLY_SECRET)))
        admin.execute("GRANT USAGE ON SCHEMA demo_catalog TO readonly")
        admin.execute("GRANT SELECT ON demo_catalog.demo_nodes, demo_catalog.demo_services TO readonly")
    yield port


def test_psycopg_pg16_synthetic_readonly_catalog_and_real_sql_permissions(
    isolated_postgres, tmp_path: Path,
):
    source = sample_mapping(tmp_path)
    current_bytes = source.read_bytes()
    target = LinuxTarget(mode="local", root="/srv/geopublisher/synthetic", postgres_port=isolated_postgres)
    session = SimpleNamespace(target=target)
    connection = {
        "database": "demo_db",
        "username": "readonly",
        "password": SYNTHETIC_READONLY_SECRET,
    }
    clean = probe_catalog(target, session, source, output=tmp_path / "clean-evidence", **connection)
    assert clean["status"] == "READ_ONLY_EVIDENCE_READY_NOT_APPROVED"
    record = json.loads(Path(clean["review"]).read_text("utf-8"))
    assert record["database_identity"]["read_only"] == "on"
    assert record["database_identity"]["server_version_num"].startswith("16")
    assert record["schema_verified"] is False
    assert record["database_modified"] is False
    assert SYNTHETIC_READONLY_SECRET not in Path(clean["review"]).read_text("utf-8")
    altered = json.loads(source.read_text("utf-8"))
    altered["existing_parents"][0]["title"] = "WRONG-PARENT"
    altered_file = tmp_path / "wrong-parent.json"
    altered_file.write_text(json.dumps(altered), encoding="utf-8")
    blocked = probe_catalog(
        target, session, altered_file,
        output=tmp_path / "blocked-evidence", **connection,
    )
    assert blocked["status"] == "BLOCKED_PENDING_HUMAN_REVIEW"
    assert any("basemap" in reason for reason in blocked["blocking_reasons"])
    with psycopg.connect(
        host="127.0.0.1", port=isolated_postgres, dbname="demo_db",
        user="readonly", password=SYNTHETIC_READONLY_SECRET,
    ) as conn:
        assert conn.execute("SELECT COUNT(*) FROM demo_catalog.demo_nodes").fetchone()[0] == 1
        assert conn.execute("SELECT COUNT(*) FROM demo_catalog.demo_services").fetchone()[0] == 0
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            conn.execute("INSERT INTO demo_catalog.demo_nodes (sys,code,namec) "
                         "VALUES ('0','forbidden','should-never-write')")
        conn.rollback()
        assert conn.execute("SELECT COUNT(*) FROM demo_catalog.demo_nodes").fetchone()[0] == 1
    assert source.read_bytes() == current_bytes
